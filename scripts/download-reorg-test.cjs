const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.openManager('download'))
  await p.waitForTimeout(1200)
  const tabs = await p.locator('.page.download .tabs button').allInnerTexts()
  console.log('download tabs:', tabs.join(' / '))
  await p.locator('.page.download .tabs button:has-text("资源包")').click({ force: true })
  await p.waitForTimeout(2500)
  console.log('online rows:', await p.locator('.online-hit').count())
  await p.evaluate(() => window.scl.openManager('versions'))
  await p.waitForTimeout(800)
  await p.locator('button:has-text("安装新版本")').click({ force: true })
  await p.waitForTimeout(800)
  console.log('install tabs:', (await p.locator('.page.download .tabs button').allInnerTexts()).join(' / '))
  console.log('has back:', await p.locator('button:has-text("版本列表")').count())
  await p.screenshot({ path: '/tmp/versions-install.png' })
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
