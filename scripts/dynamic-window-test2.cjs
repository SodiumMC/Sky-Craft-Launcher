const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.saveConfig({ dynamicWindow: false }))
  await p.evaluate(() => window.scl.openManager('settings'))
  await p.waitForTimeout(900)
  console.log('off manager:', await p.evaluate(() => [innerWidth, innerHeight]))
  await p.evaluate(() => window.scl.openAccount())
  await p.waitForTimeout(800)
  console.log('off account:', await p.evaluate(() => [innerWidth, innerHeight]), 'modal:', await p.locator('.modal').count())
  await p.evaluate(() => window.scl.saveConfig({ dynamicWindow: true }))
  await p.evaluate(() => window.scl.focusHome())
  await p.waitForTimeout(800)
  console.log('restored home:', await p.evaluate(() => [innerWidth, innerHeight]))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
