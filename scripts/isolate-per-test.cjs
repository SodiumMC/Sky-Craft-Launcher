const { _electron: electron } = require('playwright-core')
const fs = require('fs')
const os = require('os')
const path = require('path')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.saveConfig({ isolatedVersions: { '1.20.1': true } }))
  const mods = await p.evaluate(() => window.scl.listMods('1.20.1'))
  const dir = path.join(os.homedir(), 'Library/Application Support/ModrinthApp/meta/versions/1.20.1/game/mods')
  console.log('isolated mods count:', mods.length, 'dir exists:', fs.existsSync(dir))
  const cfg = await p.evaluate(() => window.scl.getState().then((s) => s.config))
  console.log('isolatedVersions:', JSON.stringify(cfg.isolatedVersions))
  await p.evaluate(() => window.scl.saveConfig({ isolatedVersions: {} }))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
