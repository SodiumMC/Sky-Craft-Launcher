const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.openManager('settings'))
  await p.waitForTimeout(900)
  const slider = p.locator('.tilt-control input[type=range]')
  await slider.fill('0')
  await p.mouse.move(50, 50)
  await p.waitForTimeout(400)
  const off = await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--tilt-x').trim())
  await slider.fill('50')
  await p.mouse.move(500, 300)
  await p.waitForTimeout(400)
  const half = await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--tilt-x').trim())
  await slider.fill('100')
  console.log('off:', off, 'half:', half)
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
