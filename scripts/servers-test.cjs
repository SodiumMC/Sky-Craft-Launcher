const { _electron: electron } = require('playwright-core')
const fs = require('fs')
const os = require('os')
const path = require('path')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.saveConfig({ isolatedVersions: { tmpiso: true } }))
  const ok = await p.evaluate(() => window.scl.saveServers([{ name: '测试服', ip: 'mc.example.com:25565' }], 'tmpiso'))
  const list = await p.evaluate(() => window.scl.listServers('tmpiso'))
  console.log('save:', ok, 'list:', JSON.stringify(list))
  const dir = path.join(os.homedir(), 'Library/Application Support/ModrinthApp/meta/versions/tmpiso/game')
  if (fs.existsSync(dir)) fs.rmSync(dir, { recursive: true, force: true })
  await p.evaluate(() => window.scl.saveConfig({ isolatedVersions: {} }))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
