const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.waitForSelector('.update-card', { timeout: 15000 })
  await p.waitForTimeout(600)
  console.log('popup size:', await p.evaluate(() => [innerWidth, innerHeight]))
  console.log('views hidden:', await p.evaluate(() => [...document.querySelectorAll('.view')].every((v) => getComputedStyle(v).visibility === 'hidden')))
  await p.screenshot({ path: '/tmp/update-layer.png' })
  await p.click('.update-card button:has-text("稍后")', { timeout: 5000 })
  await p.waitForTimeout(800)
  console.log('restored:', await p.evaluate(() => [innerWidth, innerHeight]), 'home visible:', await p.locator('.view.on .launch-card').count())
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
