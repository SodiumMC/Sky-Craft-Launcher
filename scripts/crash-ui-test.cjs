const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.launch('1.21.1-21.1.249'))
  await p.waitForSelector('.crash-title', { timeout: 30000 })
  console.log('size:', await p.evaluate(() => [innerWidth, innerHeight]))
  console.log('title:', await p.locator('.crash-title').innerText())
  console.log('detail:', (await p.locator('.update-notes').innerText()).slice(0, 120))
  await p.screenshot({ path: '/tmp/crash-dialog.png' })
  await p.locator('button:has-text("知道了")').click()
  await p.waitForTimeout(600)
  console.log('closed size:', await p.evaluate(() => [innerWidth, innerHeight]))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
