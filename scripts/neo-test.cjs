const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  const v = await p.evaluate(() => window.scl.neoVersions('1.21.1'))
  console.log('neo versions:', Array.isArray(v) ? v.length : 'fail', Array.isArray(v) ? v[v.length - 1] : '')
  await p.click('.home-dock .dock-item:has-text("下载")')
  await p.waitForSelector('.manager-dock', { timeout: 20000 })
  await p.waitForTimeout(2000)
  await p.click('.detail-pane .btn.primary.wide')
  await p.waitForTimeout(300)
  console.log('choices:', await p.locator('.loader-choice').count())
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
