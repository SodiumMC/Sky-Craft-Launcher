const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.saveConfig({ updateUrl: 'http://127.0.0.1:8765/latest.json' }))
  console.log('check:', JSON.stringify(await p.evaluate(() => window.scl.checkUpdate())))
  await p.waitForSelector('.update-card', { timeout: 10000 })
  console.log('dialog:', (await p.locator('.update-card').innerText()).replace(/\n/g, ' | ').slice(0, 120))
  await p.screenshot({ path: '/tmp/update-dialog.png' })
  await p.evaluate(() => window.scl.saveConfig({ updateUrl: '' }))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
