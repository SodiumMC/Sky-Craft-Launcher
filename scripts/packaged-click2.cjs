const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: '/Applications/SCL.app/Contents/MacOS/SCL', env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.waitForSelector('.update-card', { timeout: 15000 })
  await p.click('.update-card button:has-text("稍后")', { timeout: 5000 })
  await p.waitForTimeout(300)
  console.log('close ok:', (await p.locator('.update-card').count()) === 0)
  await p.evaluate(() => window.scl.openManager('settings'))
  await p.waitForTimeout(900)
  await p.click('button:has-text("检查更新")', { timeout: 5000 })
  await p.waitForTimeout(1000)
  console.log('check ok:', await p.locator('.sgroup.about small').last().innerText().catch(() => ''))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
