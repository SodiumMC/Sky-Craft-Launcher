const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.click('.home-dock .dock-item:has-text("设置")', { force: true })
  await p.waitForSelector('.manager-dock', { timeout: 20000 })
  await p.waitForTimeout(900)
  const sw = p.locator('.srow:has-text("灵动窗口") input[type=checkbox]')
  await sw.click({ force: true })
  await p.waitForTimeout(900)
  console.log('after off size:', await p.evaluate(() => [innerWidth, innerHeight]))
  await p.click('.view.on .account', { force: true })
  await p.waitForTimeout(800)
  console.log('account size:', await p.evaluate(() => [innerWidth, innerHeight]), 'modal:', await p.locator('.modal').count())
  await p.click('.modal-head .icon-btn', { force: true })
  await p.waitForTimeout(600)
  await p.click('.view.on .manager-dock .dock-item:has-text("启动")', { force: true })
  await p.waitForTimeout(700)
  console.log('home size:', await p.evaluate(() => [innerWidth, innerHeight]))
  // 恢复默认
  await p.click('.home-dock .dock-item:has-text("设置")', { force: true })
  await p.waitForTimeout(700)
  await sw.click({ force: true })
  await p.waitForTimeout(700)
  console.log('restored:', await p.evaluate(() => [innerWidth, innerHeight]))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
