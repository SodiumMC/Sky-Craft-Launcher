const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  const res = await p.evaluate(() => window.scl.launch('neoforge-21.1.264'))
  console.log('launch:', JSON.stringify(res).slice(0, 140))
  await p.waitForTimeout(18000)
  const logs = await p.evaluate(() => window.scl.getRecentLogs())
  const errors = logs.filter((l) => /Exception|Error|Caused by/.test(l.text)).slice(0, 6)
  console.log('errors:', errors.map((l) => l.text.slice(0, 180)).join('\n---\n'))
  console.log('tail:', logs.slice(-2).map((l) => l.text.slice(0, 100)).join(' | '))
  console.log('running:', await p.evaluate(() => window.scl.getState().then((s) => Boolean(s.running))))
  await p.evaluate(() => window.scl.killGame()).catch(() => {})
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
