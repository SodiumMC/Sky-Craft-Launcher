const { _electron: electron } = require('playwright-core')
const cjk = (p) => p.evaluate(() => [...new Set(document.body.innerText.split('\n').map(s => s.trim()).filter(s => /[\u4e00-\u9fa5]/.test(s)))])
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.openManager('versions'))
  await p.waitForTimeout(1200)
  await p.evaluate(() => {
    const row = document.querySelector('.vtable tbody tr')
    const buttons = row ? Array.from(row.querySelectorAll('button')) : []
    buttons[1]?.click()
  })
  await p.waitForTimeout(900)
  console.log('version-settings:', JSON.stringify(await cjk(p)))
  await p.locator('.modal-head .icon-btn').first().click({ force: true }).catch(() => {})
  await p.waitForTimeout(400)
  await p.evaluate(() => window.scl.openManager('settings'))
  await p.waitForTimeout(800)
  await p.locator('button:has-text("Report a bug")').click({ force: true })
  await p.waitForTimeout(800)
  console.log('bug-dialog:', JSON.stringify(await cjk(p)))
  await p.screenshot({ path: '/tmp/en-bug.png' })
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
