const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  const nw = app.waitForEvent('window').catch(() => null)
  await p.click('.home-avatar')
  await p.waitForSelector('.modal .account-row', { timeout: 10000 })
  await p.waitForTimeout(700)
  console.log('dialog:', await p.locator('.modal .ms-login').count(), 'size:', await p.evaluate(() => [innerWidth, innerHeight]))
  await p.click('.modal-head .icon-btn')
  await p.waitForTimeout(700)
  console.log('back home:', await p.evaluate(() => [innerWidth, innerHeight]), 'home visible:', await p.locator('.view.on .launch-card').count())
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
