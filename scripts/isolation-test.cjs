const fs = require('fs')
const path = require('path')
const os = require('os')
const { _electron: electron } = require('playwright-core')
;(async () => {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: process.cwd(), env })
  const p = await app.firstWindow()
  await p.waitForSelector('.launch-card', { timeout: 20000 })
  await p.evaluate(() => window.scl.saveConfig({ versionIsolation: true, selectedVersion: '1.21.1-Fabric' }))
  const res = await p.evaluate(() => window.scl.launch('1.21.1-Fabric'))
  console.log('launch:', JSON.stringify(res))
  await p.waitForTimeout(12000)
  const inst = path.join(os.homedir(), '.minecraft', 'versions', '1.21.1-Fabric', 'game')
  console.log('instance exists:', fs.existsSync(inst), 'options:', fs.existsSync(path.join(inst, 'options.txt')))
  console.log('mods in instance:', await p.evaluate(() => window.scl.listMods('1.21.1-Fabric')))
  await p.evaluate(() => window.scl.killGame()).catch(() => {})
  await p.waitForTimeout(1500)
  await p.evaluate(() => window.scl.saveConfig({ versionIsolation: false }))
  await app.close().catch(() => {})
  process.exit(0)
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
